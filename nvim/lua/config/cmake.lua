local M = {}

local function notify(msg, level)
	vim.notify(msg, level or vim.log.levels.INFO, {
		title = "CMake",
	})
end

local function find_project_root()
	local file = vim.api.nvim_buf_get_name(0)
	local start = file ~= "" and vim.fs.dirname(file) or vim.fn.getcwd()

	local root = vim.fs.find("CMakeLists.txt", {
		path = start,
		upward = true,
		type = "file",
	})[1]

	if not root then
		notify("Could not find CMakeLists.txt", vim.log.levels.ERROR)
		return nil
	end

	return vim.fs.dirname(root)
end

function M.build_run()
	local root = find_project_root()
	if not root then
		return
	end

	local build_dir = root .. "/build"

	-- Configure the project.
	notify("Configuring project...")

	vim.fn.jobstart({
		"cmake",
		"-S",
		root,
		"-B",
		build_dir,
	}, {
		cwd = root,
		on_exit = function(_, code)
			vim.schedule(function()
				if code ~= 0 then
					notify("CMake configuration failed", vim.log.levels.ERROR)
					return
				end

				-- Compile the project.
				notify("Building project...")

				vim.fn.jobstart({
					"cmake",
					"--build",
					build_dir,
					"--parallel",
				}, {
					cwd = root,
					on_exit = function(_, build_code)
						vim.schedule(function()
							if build_code ~= 0 then
								notify("Build failed", vim.log.levels.ERROR)
								return
							end

							-- Find the executable generated by CMake.
							local result = vim.system({
								"cmake",
								"--build",
								build_dir,
								"--target",
								"help",
							}, { cwd = root, text = true }):wait()

							if result.code ~= 0 then
								notify("Could not inspect build targets", vim.log.levels.ERROR)
								return
							end

							local executables = {}

							local function scan(dir)
								for name, kind in vim.fs.dir(dir) do
									local path = dir .. "/" .. name

									if kind == "file" and vim.fn.executable(path) == 1 then
										executables[#executables + 1] = path
									end
								end
							end

							scan(build_dir)

							if #executables == 0 then
								notify("Build succeeded, but no executable was found", vim.log.levels.WARN)
								return
							end

							vim.ui.select(executables, {
								prompt = "Run executable:",
							}, function(choice)
								if not choice then
									return
								end

								vim.cmd("botright 15split")
								vim.cmd("enew")

								local buf = vim.api.nvim_get_current_buf()
								local win = vim.api.nvim_get_current_win()

								vim.bo[buf].buftype = "nofile"
								vim.bo[buf].bufhidden = "hide"
								vim.bo[buf].swapfile = false

								vim.fn.jobstart({ choice }, {
									cwd = root,
									term = true,

									on_exit = function(_, exit_code)
										vim.schedule(function()
											if vim.api.nvim_buf_is_valid(buf) then
												if
													vim.api.nvim_win_is_valid(win)
													and vim.api.nvim_win_get_buf(win) == buf
												then
													vim.api.nvim_win_close(win, true)
												end

												if vim.api.nvim_buf_is_valid(buf) then
													vim.api.nvim_buf_delete(buf, { force = true })
												end
											end

											if exit_code ~= 0 then
												notify("Program exited with code " .. exit_code, vim.log.levels.WARN)
											end
										end)
									end,
								})

								vim.cmd("startinsert")
							end)
						end)
					end,
				})
			end)
		end,
	})
end

return M
